const here = dirname(fileURLToPath(import.meta.url));

const screens = await fetch(`${BASE}/__screens`).then(r => r.json()).catch(() => null);
if (!screens) {
  console.error(`Nothing is listening on ${BASE}. Start it with: node test-lab/freight-platform/server.js`);
  process.exit(1);
}
const defects = await fetch(`${BASE}/__defects`).then(r => r.json());

