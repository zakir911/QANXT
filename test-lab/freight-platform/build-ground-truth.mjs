/**
 * Writes ground-truth.json from the running application.
 *
 * Generated rather than hand-written, because a hand-written inventory of 137 screens is
 * wrong within a week and nobody notices until a measurement quietly uses it. The screen
 * list, the shapes and the defect catalogue all come from the application itself, so the
 * ground truth cannot disagree with the thing it describes.
 *
 * The journey outcomes are the one part a human supplies, because "which journeys the
 * shipped build breaks" is a claim about behaviour and belongs with evidence: run
 * `node journeys.mjs --dirty` and the outcomes below are what it printed.
 *
 *   node build-ground-truth.mjs [--port 4400]
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

